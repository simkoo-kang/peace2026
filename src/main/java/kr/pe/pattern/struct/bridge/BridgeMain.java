package kr.pe.pattern.struct.bridge;

/**
 * <pre>
 * 소프트웨어 디자인 패턴에서 브릿지 패턴(Bridge Pattern)은 구현(Implementation)과 추상화(Abstraction)를 분리하여,
 *  두 부분이 독립적으로 확장할 수 있도록 연결(다리)해주는 구조적 패턴입니다.
 * 
 * 쉽게 말해, "상속"을 통한 확장의 한계를 극복하기 위해 "상속(Inheritance) 대신 조립(Composition)"을 사용하는 대표적인 패턴입니다.
 * 
 * 
 * 💡 왜 브릿지 패턴을 쓸까요? (문제 상황)
 *  - 예를 들어 모양(Shape) 클래스(원, 사각형)가 있고, 각 모양을 색상(Color)(빨강, 파랑)별로 구현해야 한다고 가정해 봅시다.
 *    만약 일반적인 상속 구조를 사용하면 다음과 같이 클래스가 폭발적으로 늘어납니다.
 *    Shape (최상위)
 *     - RedCircle, BlueCircle, RedRectangle, BlueRectangle...\
 * 
 *    여기에 초록색이 추가되면 클래스 2개가 더 필요하고,
 *    삼각형이 추가되면 색상별로 3개가 더 필요해집니다. (종류 × 색상 만큼 클래스 개수 폭발)
 * 
 * 
 * 🏗️ 구조 및 핵심 개념
 *  - 브릿지 패턴은 이를 모양(추상화)과 색상(구현) 두 개의 독립된 계층으로 쪼갠 뒤,
 *    모양이 색상을 인터페이스로 참조(조립)하는 방식으로 해결합니다.
 * 1. Abstraction (추상화 계층): 상위 수준의 제어 로직을 담고 있으며, 구현 계층의 인스턴스를 참조합니다.
 * 2. RefinedAbstraction: 추상화 계층을 상속받아 세부 기능을 확장한 클래스입니다. (예: 원, 사각형)
 * 3. Implementor (구현 계층 인터페이스): 실제 하위 동작을 수행할 메서드들을 정의합니다. (예: 색상 적용 기능)
 * 4. ConcreteImplementor: 구현 인터페이스를 실제로 구현한 클래스입니다. (예: 빨강, 파랑)
 * 
 * 
 * ⚖️ 장점과 단점
 * 1. 장점 ⭕
 *  - 독립적인 확장: 모양을 추가해도 색상 코드를 건드릴 필요가 없고, 반대도 마찬가지입니다.
 *  - 결합도 낮춤: 클라이언트 코드는 추상화된 인터페이스만 보면 되므로 구현 세부 사항과 분리됩니다.
 *  - OCP(개방-폐쇄 원칙) 만족: 기존 코드를 수정하지 않고 새로운 모양이나 색상을 쉽게 추가합니다.
 * 2. 단점 ❌
 *  - 복잡도 증가: 인터페이스와 추상 클래스가 늘어나 전체적인 구조가 복잡해질 수 있습니다.
 *  - 디자인 직관성 저하: 처음 코드를 읽는 사람에게는 직관적으로 이해하기 어려울 수 있습니다.
 * 
 * 
 * 🎯 언제 사용하나요?
 * - 하나의 기능이 여러 가지 독립된 차원(예: OS별 드라이버 기능, GUI 윈도우 컴포넌트의 스타일 등)으로 변해야 할 때.
 * - 런타임(실행 도중)에 구현체를 유연하게 교체하고 싶을 때.
 * - 부모 클래스가 너무 많은 자식 클래스를 가지게 되어 상속 구조가 감당하기 힘들 정도로 복잡해졌을 때.
 * 
 * PC  2026. 9. 10. 오후 9:15:18
 * </pre>
 */
public class BridgeMain {

	/**
	 * <pre>
	 * 
	 * PC 2026. 9. 10. 오후 9:15:18
	 * </pre>
	 *
	 * @param args
	 */
	public static void main(String[] args) {
		// 빨간 원 만들기 (원 + 빨간색 조립)
		Shape redCircle = new Circle(new RedColor());
		redCircle.draw(); // 출력: 빨간색 원을 그립니다.

		// 파란 사각형 만들기 (사각형 + 파란색 조립)
		Shape blueRectangle = new Rectangle(new BlueColor());
		blueRectangle.draw(); // 출력: 파란색 사각형을 그립니다.
	}

}
